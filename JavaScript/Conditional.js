//Simple if

if(5==5)
{
    console.log("JavaScript")
}

console.log("Hello")

//if..else
if(5==="5")
{
    console.log("JavaScript")
}
else
{
    console.log("Java")
}

//if..else..if   (Multiple condition check)

let mark = 74

if(mark>=90 && mark<=100)
{
    console.log("Grade A")
}   
else if(mark>=75 && mark<=89)
{
    console.log("Grade B")
}
else if(mark>=65 && mark<=74)
{
    console.log("Grade C")
}
else if(mark>=55 && mark<=64)
{
    console.log("Grade D")
}
else if(mark>=35 && mark<=54)
{
    console.log("Grade E")
}
else
{
    console.log("Fail")
}





